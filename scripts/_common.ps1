<#
.SYNOPSIS
    Shared helpers for Phoresis PowerShell scripts.

.DESCRIPTION
    Loaded via `. "$PSScriptRoot\_common.ps1"` from each script.
    Provides logging primitives + .env reading + a few small utilities.

.NOTES
    Targets Windows PowerShell 5.1+ (Windows 11 default).
#>

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# ---------- logging ----------

function Write-Step {
    param([string]$Message)
    Write-Host ""
    Write-Host "==> $Message" -ForegroundColor Cyan
}

function Write-Sub {
    param([string]$Message)
    Write-Host "    $Message" -ForegroundColor DarkGray
}

function Write-Ok {
    param([string]$Message)
    Write-Host "    [OK] $Message" -ForegroundColor Green
}

function Write-Warn {
    param([string]$Message)
    Write-Host "    [WARN] $Message" -ForegroundColor Yellow
}

function Write-Err {
    param([string]$Message)
    Write-Host "    [ERROR] $Message" -ForegroundColor Red
}

# ---------- .env helpers ----------

function Read-EnvFile {
    param([Parameter(Mandatory)][string]$Path)
    if (-not (Test-Path $Path)) { return @{} }
    $env = @{}
    Get-Content -Path $Path | ForEach-Object {
        $line = $_.Trim()
        if (-not $line -or $line.StartsWith('#')) { return }
        $eq = $line.IndexOf('=')
        if ($eq -lt 1) { return }
        $key = $line.Substring(0, $eq).Trim()
        $val = $line.Substring($eq + 1).Trim()
        if ($val -match '^"(.*)"$' -or $val -match "^'(.*)'$") { $val = $matches[1] }
        $env[$key] = $val
    }
    return $env
}

function Write-EnvFile {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][hashtable]$Map
    )
    $lines = @("# Phoresis environment - generated by install.ps1")
    foreach ($k in $Map.Keys | Sort-Object) {
        $v = $Map[$k]
        if ($v -match '\s') { $v = '"' + $v + '"' }
        $lines += "$k=$v"
    }
    Set-Content -Path $Path -Value $lines -Encoding UTF8
}

# ---------- elevation ----------

function Test-Admin {
    $id = [System.Security.Principal.WindowsIdentity]::GetCurrent()
    $p  = New-Object System.Security.Principal.WindowsPrincipal($id)
    return $p.IsInRole([System.Security.Principal.WindowsBuiltInRole]::Administrator)
}

function Assert-Admin {
    if (-not (Test-Admin)) {
        Write-Err "This script must be run as Administrator."
        Write-Sub "Right-click the script > 'Run with PowerShell as Administrator', or"
        Write-Sub "open an elevated PowerShell and re-run from there."
        exit 1
    }
}

# ---------- docker / compose helpers ----------

$Script:RepoRoot   = (Get-Item "$PSScriptRoot\..").FullName
$Script:DockerDir  = Join-Path $Script:RepoRoot 'docker'
$Script:ComposeBase = @('-f', (Join-Path $Script:DockerDir 'docker-compose.yml'))

function Get-ComposeArgs {
    param([switch]$WithGpu)
    $argv = $Script:ComposeBase
    if ($WithGpu) { $argv += @('-f', (Join-Path $Script:DockerDir 'compose.gpu.yml')) }
    $envFile = Join-Path $Script:RepoRoot '.env'
    if (Test-Path $envFile) { $argv += @('--env-file', $envFile) }
    return $argv
}

# ---------- waiting ----------

function Wait-HttpOk {
    param(
        [Parameter(Mandatory)][string]$Url,
        [int]$TimeoutSeconds = 90,
        [int]$IntervalSeconds = 3
    )
    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    while ((Get-Date) -lt $deadline) {
        try {
            $resp = Invoke-WebRequest -Uri $Url -SkipCertificateCheck -UseBasicParsing -TimeoutSec 5 -ErrorAction Stop
            if ($resp.StatusCode -eq 200) { return $true }
        } catch {
            # not yet ready - loop
        }
        Start-Sleep -Seconds $IntervalSeconds
    }
    return $false
}

# ---------- storage paths ----------

function Get-MediaDir {
    <#
    .SYNOPSIS
        Resolve the host-side media directory.
    .DESCRIPTION
        Reads PHORESIS_MEDIA_DIR from .env if present, falls back to the
        compose default `<repo>/_phoresis_data/media`.
    #>
    $envMap = Read-EnvFile (Join-Path $Script:RepoRoot '.env')
    $mediaDir = $envMap['PHORESIS_MEDIA_DIR']
    if ($mediaDir) {
        return ($mediaDir -replace '/', '\')
    }
    return (Join-Path $Script:DockerDir '_phoresis_data\media')
}
