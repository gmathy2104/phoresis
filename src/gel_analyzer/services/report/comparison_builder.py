    def build(self) -> BytesIO:
        """
        Build the complete Word document.

        Sections are gated by ``_should_include()`` and numbered dynamically
        so that only selected sections appear with sequential numbering.

        Returns:
            BytesIO buffer containing the Word document
        """
        logger.info(f"Building Lane Comparison Word report for '{self.data.name}'")

        # Cover page always included
        try:
            self.add_cover_page()
        except Exception as e:
            logger.error(f"Failed to add cover page: {e}")

        # Section map: (section_key, method_name, description)
        section_map = [
            ("overview", "add_comparison_overview", "comparison overview"),
            ("sample_summary", "add_sample_summary_table", "sample summary table"),
            ("digital_gel", "add_digital_gel_comparison", "digital gel comparison"),
            ("gel_images", "add_gel_images", "gel images"),
            ("band_comparison", "add_band_comparison_table", "band comparison table"),
            ("lane_details", "add_lane_detail_sections", "lane detail sections"),
            ("poi_purity", "add_poi_purity_chart", "POI purity chart"),
            ("materials_methods", "add_materials_and_methods", "materials and methods"),
        ]

        section_number = 1
        for key, method_name, description in section_map:
            if not self._should_include(key):
                continue
            try:
                method = getattr(self, method_name)
                method(section_number=section_number)
                section_number += 1
            except Exception as e:
                logger.error(f"Failed to add {description}: {e}")

        # Metadata footer always included
        try:
            self.add_metadata_footer()
        except Exception as e:
            logger.error(f"Failed to add metadata footer: {e}")

        logger.info(f"Lane Comparison Word report built successfully for '{self.data.name}'")
        return self._save()
