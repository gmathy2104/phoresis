    def _annotate_gel_image(self, gel_image_id, lanes):
        """
        Load gel image from DB and draw lane/band annotations with Pillow.

        Args:
            gel_image_id: PK of GelImage model
            lanes: list of ComparisonLaneData for lanes on this gel

        Returns:
            BytesIO with annotated PNG, or None if image not available
        """
        from PIL import Image, ImageDraw, ImageFont

        from gel_analyzer.models import GelImage

        gel_image = GelImage.objects.get(pk=gel_image_id)
        image_file = gel_image.display_file or gel_image.original_file
        if not image_file:
            return None

        # Load image and convert to RGBA for overlay compositing
        img = Image.open(image_file).convert("RGBA")

        # Create transparent overlay for annotations
        overlay = Image.new("RGBA", img.size, (0, 0, 0, 0))
        draw = ImageDraw.Draw(overlay)

        # Color palette (matching frontend gel-overview-panel.js)
        LANE_FILL = (59, 130, 246, 60)
        LANE_BORDER = (59, 130, 246, 200)
        BAND_COLORS = {
            "Protein of Interest": (168, 85, 247, 120),
            "Other": (34, 197, 94, 120),
            "MW Ladder": (249, 115, 22, 120),
        }
        LABEL_BG = (0, 0, 0, 160)
        LABEL_FG = (255, 255, 255, 255)

        # Scale font size proportionally with image width
        try:
            font_size = max(14, img.width // 80)
            font_small_size = max(11, img.width // 100)
            font = ImageFont.truetype("arial.ttf", font_size)
            font_small = ImageFont.truetype("arial.ttf", font_small_size)
        except OSError:
            try:
                # macOS fallback
                font = ImageFont.truetype("/System/Library/Fonts/Helvetica.ttc", max(14, img.width // 80))
                font_small = ImageFont.truetype("/System/Library/Fonts/Helvetica.ttc", max(11, img.width // 100))
            except OSError:
                font = ImageFont.load_default()
                font_small = font

        for lane in lanes:
            outline = outline_of_row(lane)
            if outline is None:
                continue

            # Draw the lane by its outline (fill + border): a tilted lane's box takes in its neighbours
            draw.polygon([(x, y) for x, y in outline], fill=LANE_FILL, outline=LANE_BORDER, width=2)
            lx, ly = top_left(outline)
            name_x, name_y = bottom_centre(outline)

            # Lane label at top with dark background pill
            label = f"L{lane.lane_number}"
            bbox = draw.textbbox((0, 0), label, font=font)
            tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
            draw.rectangle([lx, ly - th - 6, lx + tw + 10, ly], fill=LABEL_BG)
            draw.text((lx + 5, ly - th - 3), label, fill=LABEL_FG, font=font)

            # Sample name below lane, centered
            if lane.sample_name:
                short_name = lane.sample_name[:20]
                nbbox = draw.textbbox((0, 0), short_name, font=font_small)
                nw = nbbox[2] - nbbox[0]
                nh = nbbox[3] - nbbox[1]
                nx = name_x - nw // 2
                ny = name_y + 2
                draw.rectangle([nx - 2, ny, nx + nw + 2, ny + nh + 4], fill=LABEL_BG)
                draw.text((nx, ny + 2), short_name, fill=LABEL_FG, font=font_small)

            # Draw bands
            for band in lane.bands:
                bx, by = band.bbox_x, band.bbox_y
                bw, bh = band.bbox_width, band.bbox_height
                if not all(v is not None for v in (bx, by, bw, bh)):
                    continue

                color = BAND_COLORS.get(band.band_type, BAND_COLORS["Other"])
                draw.rectangle([bx, by, bx + bw, by + bh], fill=color, outline=color[:3] + (220,), width=1)

                # MW label to the right of band (if calibrated)
                if band.estimated_mw_kda:
                    mw_label = f"{band.estimated_mw_kda:.0f} kDa"
                    mbbox = draw.textbbox((0, 0), mw_label, font=font_small)
                    mw_w = mbbox[2] - mbbox[0]
                    mw_h = mbbox[3] - mbbox[1]
                    mx = bx + bw + 3
                    my = by + (bh - mw_h) // 2
                    draw.rectangle([mx - 1, my - 1, mx + mw_w + 3, my + mw_h + 1], fill=LABEL_BG)
                    draw.text((mx + 1, my), mw_label, fill=LABEL_FG, font=font_small)

        # Composite overlay onto original image
        result = Image.alpha_composite(img, overlay)
        result = result.convert("RGB")  # Word needs RGB

        buf = BytesIO()
        result.save(buf, format="PNG", quality=95)
        buf.seek(0)
        return buf

    def _cluster_bands_by_mw(self, tolerance_pct: float) -> list:
        """
        Cluster bands across lanes by MW within tolerance.

        Greedy algorithm: sort all bands by MW descending, assign each to
        the nearest existing cluster if within tolerance, else create new cluster.
        One band per lane per cluster to avoid double-counting.

        Args:
            tolerance_pct: Percentage tolerance (e.g. 5 for ±5%)

        Returns:
            List of dicts: {mw: float (avg), bands: {lane_idx: band_info}}
        """
        all_bands = []
        for lane_idx, lane in enumerate(self.data.lanes):
            for band in lane.bands:
                if band.estimated_mw_kda and band.estimated_mw_kda > 0:
                    all_bands.append(
                        {
                            "lane_idx": lane_idx,
                            "mw": band.estimated_mw_kda,
                            "pct_lane": band.relative_percent_lane,
                            "band_type": band.band_type,
                        }
                    )

        # Sort by MW descending
        all_bands.sort(key=lambda b: b["mw"], reverse=True)

        clusters = []
        for band in all_bands:
            merged = False
            for cluster in clusters:
                pct_diff = abs(band["mw"] - cluster["mw"]) / cluster["mw"] * 100
                if pct_diff <= tolerance_pct and band["lane_idx"] not in cluster["bands"]:
                    cluster["bands"][band["lane_idx"]] = band
                    # Recalculate cluster average MW
                    mws = [b["mw"] for b in cluster["bands"].values()]
                    cluster["mw"] = sum(mws) / len(mws)
                    merged = True
                    break

            if not merged:
                clusters.append(
                    {
                        "mw": band["mw"],
                        "bands": {band["lane_idx"]: band},
                    }
                )

        # Sort clusters by MW descending
        clusters.sort(key=lambda c: c["mw"], reverse=True)
        return clusters

    def add_band_comparison_table(self, section_number: int = 5):
        """Add MW-aligned band comparison table with tolerance-based clustering."""
        try:
            self.document.add_page_break()
            self._add_section_heading(f"{section_number}. BAND COMPARISON")

            if not self.data.lanes:
                self._add_paragraph("No lanes to compare.", font_size=SMALL_SIZE)
                return

            # Check if all lanes have calibration
            if not self.data.all_calibrated:
                self._add_paragraph(
                    f"Note: Only {self.data.calibrated_count} of {self.data.lane_count} lanes "
                    "have MW calibration. Uncalibrated lanes show band position only.",
                    font_size=SMALL_SIZE,
                    color=MUTED_GRAY,
                )
                self.document.add_paragraph()

            # Cluster bands by MW within tolerance
            tolerance = self.data.mw_tolerance_pct
            clusters = self._cluster_bands_by_mw(tolerance)

            if not clusters:
                self._add_paragraph(
                    "No calibrated bands available for MW-aligned comparison.", font_size=SMALL_SIZE, color=MUTED_GRAY
                )
                return

            self._add_paragraph(
                f"Bands clustered within \u00b1{tolerance:.0f}% MW tolerance.", font_size=SMALL_SIZE, color=MUTED_GRAY
            )
            self.document.add_paragraph()

            # Table headers: MW (kDa) + one % Lane column per lane
            headers = ["MW (kDa)"]
            for lane in self.data.lanes:
                headers.append(sample_text(lane)[:20])

            rows = []
            for cluster in clusters:
                row = [f"{cluster['mw']:.1f}"]

                for lane_idx in range(len(self.data.lanes)):
                    band = cluster["bands"].get(lane_idx)
                    if band and band["pct_lane"] is not None:
                        row.append(f"{band['pct_lane']:.1f}%")
                    else:
                        row.append("-")

                rows.append(row)

            self._add_data_table(headers, rows)

        except Exception as e:
            logger.error(f"Error in add_band_comparison_table: {e}")

