from pathlib import Path

from docx.shared import Inches

from gel_analyzer.services.lane_geometry.shape import outer_bbox
from phoresis_core.logging_config import get_logger

from .builder import BaseReportBuilder
from .comparison_data_collector import ComparisonLaneData, ComparisonReportData
from .constants import (
    BAND_PALETTE_HEX,
    HEADING_FONT,
    IMAGE_FULL_WIDTH,
    IMAGE_HALF_WIDTH,
    METHODOLOGY_CALIBRATION,
    METHODOLOGY_DENSITOMETRY,
    MUTED_GRAY,
    PHORESIS_ACCENT,
    PHORESIS_LOGO_PATH,
    READOUT_METHODOLOGY,
    SMALL_SIZE,
    TITLE_SIZE,
    saturation_text,
)
from .digital_gel import render_digital_gel
from .lane_crop import bottom_centre, crop_lane, outline_of_row, top_left
from .page_rows import cell_text, mean_purity_text, sample_text

logger = get_logger(__name__)


class ComparisonReportBuilder(BaseReportBuilder):
    """
    Generates comprehensive Word document for Lane Comparison reports
    using python-docx with the Phoresis brand palette.
    """

    def __init__(
        self,
        data: ComparisonReportData,
        sections: list[str] | None = None,
        band_overlay: bool = True,
    ):
        """
        Initialize the comparison report builder.

        All visuals are rendered server-side with Pillow/matplotlib.

        Args:
            data: ComparisonReportData instance with all structured report data
            sections: List of section keys to include, or None for all sections
            band_overlay: Whether to draw band overlay rectangles on gel crop images
        """
        self.data = data
        self.sections = sections
        self.band_overlay = band_overlay
        self.images = {}  # kept for BaseReportBuilder compatibility
        super().__init__()

    def _should_include(self, section_key: str) -> bool:
        """Check if a section should be included in the report."""
        if self.sections is None:
            return True
        return section_key in self.sections

    def add_cover_page(self):
        """Add the cover page (Phoresis logo if configured, then title)."""
        if PHORESIS_LOGO_PATH:
            try:
                logo_path = Path(__file__).resolve().parents[3] / PHORESIS_LOGO_PATH
                if logo_path.exists():
                    paragraph = self.document.add_paragraph()
                    from docx.enum.text import WD_ALIGN_PARAGRAPH

                    paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT
                    run = paragraph.add_run()
                    run.add_picture(str(logo_path), width=Inches(1.5))
            except Exception as e:
                logger.warning(f"Failed to add logo: {e}")

        # Spacing
        for _ in range(2):
            self.document.add_paragraph()

        # Title
        self._add_paragraph(
            "LANE COMPARISON REPORT",
            font_size=TITLE_SIZE,
            bold=True,
            color=PHORESIS_ACCENT,
            align="center",
            font_name=HEADING_FONT,
        )

        self.document.add_paragraph()

        # Comparison name
        self._add_paragraph(self.data.name, font_size=20, bold=True, align="center", font_name=HEADING_FONT)

        # Description (if provided)
        if self.data.description:
            self.document.add_paragraph()
            self._add_paragraph(self.data.description, font_size=12, align="center")

        for _ in range(2):
            self.document.add_paragraph()

        # Summary stats
        self._add_paragraph(
            f"Lanes: {self.data.lane_count} | "
            f"Assays: {self._assays_text()} | "
            f"Calibrated: {self.data.calibrated_count}/{self.data.lane_count}",
            font_size=12,
            align="center",
            color=MUTED_GRAY,
        )

        for _ in range(5):
            self.document.add_paragraph()

        # Generated info
        self._add_paragraph(
            f"Generated: {self.data.report_generated_at}", font_size=SMALL_SIZE, align="center", color=MUTED_GRAY
        )

        self._add_paragraph(
            f"Generated by: {self.data.report_generated_by}", font_size=SMALL_SIZE, align="center", color=MUTED_GRAY
        )

        self.document.add_page_break()

    def _assays_text(self) -> str:
        """The comparison's kinds (assays), as its page names them."""
        return ", ".join(kind.label for kind in self.data.kinds) or "None"

    def add_comparison_overview(self, section_number: int = 1):
        """Add comparison overview section."""
        try:
            self._add_section_heading(f"{section_number}. COMPARISON OVERVIEW")

            calibration_status = (
                f"All lanes calibrated ({self.data.calibrated_count})"
                if self.data.all_calibrated
                else f"{self.data.calibrated_count} of {self.data.lane_count} lanes calibrated"
            )

            data = [
                ("Name", self.data.name),
                ("Description", self.data.description or "N/A"),
                ("Lane Count", str(self.data.lane_count)),
                ("Assays", self._assays_text()),
                ("Calibration Status", calibration_status),
            ]
            # The mean purity of each purity kind, over the lanes compared (services/mean_purity.py).
            data += [
                (f"Mean purity · {kind.label}", mean_purity_text(kind.mean)) for kind in self.data.kinds if kind.mean
            ]
            data += [
                ("Created By", self.data.created_by_name),
                ("Created Date", self.data.created_at),
                ("Public", "Yes" if self.data.is_public else "No"),
            ]

            self._add_info_table(data, widths=[2.5, 4.5])

        except Exception as e:
            logger.error(f"Error in add_comparison_overview: {e}")

    def add_sample_summary_table(self, section_number: int = 2):
        """One table per kind (assay), as the comparison page groups its lanes: the kind's readout columns with the
        page's cells (page_rows)."""
        try:
            self._add_section_heading(f"{section_number}. SAMPLE SUMMARY")

            if not self.data.lanes:
                self._add_paragraph("No lanes in comparison.", font_size=SMALL_SIZE)
                return

            positions = {id(lane): i for i, lane in enumerate(self.data.lanes, 1)}
            for kind in self.data.kinds:
                if len(self.data.kinds) > 1:
                    self._add_section_heading(kind.label, level=2)
                headers = ["#", "Sample", "Source Analysis", "Lane #", "Condition", "Load (\u00b5g)"]
                headers += [column["label"] for column in kind.columns] + ["Notes"]
                flagged = any(lane.saturated_bands for lane in kind.lanes)
                headers += ["Saturated"] if flagged else []

                rows = []
                for lane in kind.lanes:
                    load_str = "-"
                    if lane.protein_load_ug is not None:
                        load_str = f"{lane.protein_load_ug:.1f}"
                        if lane.protein_load_type:
                            load_str += f" ({lane.protein_load_type})"
                    notes_str = (
                        (lane.notes[:30] + "...") if lane.notes and len(lane.notes) > 30 else (lane.notes or "-")
                    )
                    rows.append(
                        [
                            str(positions[id(lane)]),
                            sample_text(lane) + (" (REF)" if lane.is_reference else ""),
                            lane.analysis_name[:25] + "..." if len(lane.analysis_name) > 25 else lane.analysis_name,
                            str(lane.lane_number),
                            lane.condition or "-",
                            load_str,
                        ]
                        + [cell_text(lane, column["key"]) or "-" for column in kind.columns]
                        + [notes_str]
                        + (["⚠ " + ", ".join(lane.saturated_bands) if lane.saturated_bands else ""] if flagged else [])
                    )

                self._add_data_table(headers, rows)

        except Exception as e:
            logger.error(f"Error in add_sample_summary_table: {e}")

    def _add_lane_electropherogram(self, lane, index):
        """
        Render and add a single-lane electropherogram to the document.

        Args:
            lane: ComparisonLaneData with profile_data
            index: Lane index (for accent color selection)
        """
        from docx.enum.text import WD_ALIGN_PARAGRAPH

        if not lane.profile_data:
            return

        try:
            chart_buf = self._render_electropherogram(lane, index=index)
            if chart_buf:
                self._add_paragraph("Electropherogram:", font_size=SMALL_SIZE, bold=True)
                paragraph = self.document.add_paragraph()
                paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
                run = paragraph.add_run()
                run.add_picture(chart_buf, width=Inches(IMAGE_FULL_WIDTH))
        except Exception as e:
            logger.warning(f"Failed to render electropherogram for lane {lane.lane_number}: {e}")
            self._add_paragraph(
                f"[Failed to render profile for {lane.sample_name}]",
                font_size=SMALL_SIZE,
                color=MUTED_GRAY,
                align="center",
            )

    def _render_electropherogram(self, lane, index, dark_theme: bool = True):
        """
        Render a single-lane electropherogram with matplotlib: dark for the Word report, light (``dark_theme=False``)
        on a slide, as the densitometry deck's own curve.

        Args:
            lane: ComparisonLaneData with profile_data
            index: Lane index (for accent color selection)

        Returns:
            BytesIO with PNG image, or None
        """
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import numpy as np

        profile = lane.profile_data
        intensities = np.array(profile["intensities"], dtype=float)

        # The live densitometry chromatogram's single blue profile line; the peak markers take the gel
        # overlay's band colours (BAND_PALETTE_HEX), as the annotation view draws them.
        from .constants import CHART_PROFILE_COLOR

        PEAK_COLORS = {
            "Protein of Interest": BAND_PALETTE_HEX["POI"],  # #A855F7 purple
            "Other": BAND_PALETTE_HEX["OTHER"],  # #22C55E green (spec §5)
            "MW Ladder": BAND_PALETTE_HEX["MW_REFERENCE"],  # #F97316 orange
            "MW Reference": BAND_PALETTE_HEX["MW_REFERENCE"],  # #F97316 orange
            "Calibration Point": BAND_PALETTE_HEX.get("CALIBRATION", "#F87171"),
        }

        # --- Determine X-axis data ---
        mw_values = profile.get("mw_values")
        has_mw = mw_values and any(v is not None and v > 0 for v in mw_values)

        if has_mw:
            # Filter out None/zero MW values and pair with intensities
            paired = [
                (mw, inten) for mw, inten in zip(mw_values, intensities, strict=False) if mw is not None and mw > 0
            ]
            if not paired:
                has_mw = False

        if has_mw:
            x_values = np.array([p[0] for p in paired])
            y_values = np.array([p[1] for p in paired])
            x_label = "Molecular Weight (kDa)"
            use_log_x = True
        else:
            x_values = np.array(profile["y_positions"], dtype=float)
            y_values = intensities
            x_label = "Y Position (pixels)"
            use_log_x = False

        if len(x_values) < 2:
            return None

        # --- Line color ---
        # Single profile colour matching the live chromatogram panel —
        # lane index is no longer used to pick a hue.
        del index  # kept in signature for caller compatibility
        hex_color = CHART_PROFILE_COLOR

        # --- Create figure: dark for Word, light on a slide (the densitometry deck's own curve) ---
        ink = {
            "bg": "#1e1e22" if dark_theme else "#ffffff",
            "text": "white" if dark_theme else "#333333",
            "label": "#b0b0b0" if dark_theme else "#333333",
            "tick": "#808080" if dark_theme else "#333333",
            "spine": "#404040" if dark_theme else "#cccccc",
        }
        fig, ax = plt.subplots(figsize=(7, 2.5), dpi=200)
        fig.patch.set_facecolor(ink["bg"])
        ax.set_facecolor(ink["bg"])

        # Profile line
        ax.plot(x_values, y_values, color=hex_color, linewidth=1.5, zorder=3)

        # Area fill under curve
        ax.fill_between(x_values, 0, y_values, color=hex_color, alpha=0.25, zorder=2)

        # Log scale for MW axis
        if use_log_x:
            ax.set_xscale("log")
            ax.invert_xaxis()  # High MW on left (matching frontend)
            from matplotlib.ticker import ScalarFormatter

            ax.xaxis.set_major_formatter(ScalarFormatter())
            ax.xaxis.get_major_formatter().set_scientific(False)

        # --- Peak markers at band positions ---
        for band in lane.bands:
            # Determine x position for this band
            if has_mw and band.estimated_mw_kda and band.estimated_mw_kda > 0:
                bx = band.estimated_mw_kda
            elif band.position_y is not None and not has_mw:
                bx = float(band.position_y)
            else:
                continue

            # Find closest intensity value
            idx = np.argmin(np.abs(x_values - bx))
            by = y_values[idx]

            peak_color = PEAK_COLORS.get(band.band_type, "#9E9E9E")
            ax.plot(bx, by, "o", color=peak_color, markersize=6, markeredgecolor="white", markeredgewidth=1.5, zorder=5)

            # MW label above peak
            if band.estimated_mw_kda:
                ax.annotate(
                    f"{band.estimated_mw_kda:.0f} kDa",
                    (bx, by),
                    textcoords="offset points",
                    xytext=(0, 10),
                    fontsize=7,
                    color=ink["text"],
                    fontweight="bold",
                    ha="center",
                    zorder=6,
                )

        # --- Axis styling ---
        ax.set_xlabel(x_label, color=ink["label"], fontsize=9)
        ax.set_ylabel("Intensity", color=ink["label"], fontsize=9)
        ax.tick_params(colors=ink["tick"], labelsize=8)
        for spine in ax.spines.values():
            spine.set_color(ink["spine"])
        ax.set_ylim(bottom=0)

        # Title with sample name
        ax.set_title(
            f"{sample_text(lane)} (L{lane.lane_number})", color=ink["text"], fontsize=10, fontweight="bold", pad=8
        )

        fig.subplots_adjust(left=0.08, right=0.97, top=0.85, bottom=0.18)
        buf = BytesIO()
        fig.savefig(buf, format="png", facecolor=fig.get_facecolor())
        plt.close(fig)
        buf.seek(0)
        return buf

    def add_digital_gel_comparison(self, section_number: int = 3):
        """Add server-side rendered side-by-side digital gel."""
        from docx.enum.text import WD_ALIGN_PARAGRAPH

        try:
            self.document.add_page_break()
            self._add_section_heading(f"{section_number}. SIDE-BY-SIDE DIGITAL GEL")

            self._add_paragraph(
                "Digital lane reconstructions for visual comparison of band patterns and intensities.",
                font_size=SMALL_SIZE,
            )

            if not self.data.lanes:
                self._add_paragraph("No lanes in comparison.", font_size=SMALL_SIZE, color=MUTED_GRAY)
                return

            digital_gel = self._render_digital_gel(self.data.lanes)
            if digital_gel:
                paragraph = self.document.add_paragraph()
                paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
                run = paragraph.add_run()
                run.add_picture(digital_gel, width=Inches(IMAGE_FULL_WIDTH))
                self.document.add_paragraph()
            else:
                self._add_paragraph(
                    "[Digital gel rendering failed]", font_size=SMALL_SIZE, color=MUTED_GRAY, align="center"
                )

            # Reconstructed gel from cropped lane images
            self._add_paragraph(
                "Reconstructed gel from cropped lane images for direct visual comparison.", font_size=SMALL_SIZE
            )

            reconstructed = self._render_reconstructed_gel(self.data.lanes, show_bands=self.band_overlay)
            if reconstructed:
                paragraph = self.document.add_paragraph()
                paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
                run = paragraph.add_run()
                run.add_picture(reconstructed, width=Inches(IMAGE_FULL_WIDTH))
                self.document.add_paragraph()
            else:
                self._add_paragraph(
                    "[No gel images available for reconstruction]",
                    font_size=SMALL_SIZE,
                    color=MUTED_GRAY,
                    align="center",
                )

        except Exception as e:
            logger.error(f"Error in add_digital_gel_comparison: {e}")

    def _render_digital_gel(self, lanes):
        """Delegate to the shared renderer (footer = gel type).

        exclude_codes=() preserves the current comparison behaviour: the old
        comparison _render_digital_gel did NOT filter EMPTY lanes, so keep
        every column (do not adopt the default ('EMPTY',) filter in Ph1).
        """
        return render_digital_gel(lanes, calibration=None, footer_field="gel_type", exclude_codes=())

    def _render_reconstructed_gel(self, lanes, show_bands=False):
        """
        Stitch cropped real gel images from each lane into a single
        side-by-side "reconstructed gel" image, matching the digital gel layout.

        Optionally draws band overlay rectangles on top of each lane crop,
        scaled from the original image coordinates to the cropped/resized space.

        Args:
            lanes: list of ComparisonLaneData
            show_bands: If True, draw semi-transparent band overlays with MW labels

        Returns:
            BytesIO with PNG image, or None if no gel images available
        """
        from PIL import Image, ImageDraw, ImageFont

        from gel_analyzer.models import GelImage

        # --- Layout constants (match digital gel) ---
        LANE_GAP = 6
        HEADER_HEIGHT = 36
        BODY_HEIGHT = 400
        FOOTER_HEIGHT = 24
        ACCENT_BAR_HEIGHT = 4

        BG_COLOR = (30, 30, 34)
        HEADER_BG = (26, 26, 30)
        TEXT_COLOR = (230, 230, 230)
        TEXT_DIM = (160, 160, 160)

        ACCENT_COLORS = [
            (59, 130, 246),
            (168, 85, 247),
            (34, 197, 94),
            (249, 115, 22),
            (236, 72, 153),
            (20, 184, 166),
            (245, 158, 11),
            (99, 102, 241),
        ]

        # Band overlay colours pulled from BAND_PALETTE so the digital gel,
        # the annotated gel image, and the live UI all use the same hue
        # mapping (POI=purple, MW_REFERENCE=orange, OTHER=green).
        from .constants import BAND_PALETTE

        def _band_overlay_color(b):
            return BAND_PALETTE.get((b.band_type_code or "OTHER").upper(), BAND_PALETTE["OTHER"])["fill"]

        BAND_LABEL_BG = (15, 23, 42, 160)
        BAND_LABEL_FG = (255, 255, 255, 255)

        # --- Fonts ---
        try:
            font_small = ImageFont.truetype("arial.ttf", 10)
        except OSError:
            try:
                font_small = ImageFont.truetype("/System/Library/Fonts/Helvetica.ttc", 10)
            except OSError:
                font_small = ImageFont.load_default()

        try:
            font_band = ImageFont.truetype("arial.ttf", 8)
        except OSError:
            try:
                font_band = ImageFont.truetype("/System/Library/Fonts/Helvetica.ttc", 8)
            except OSError:
                font_band = ImageFont.load_default()

        # --- Crop each lane from its gel image ---
        # Store crop geometry so we can map band coordinates later
        lane_crops = []  # list of (crop_img or None, lane, crop_box or None)
        any_crop = False

        for lane in lanes:
            crop = None
            crop_box = None
            if lane.gel_image_id and outline_of_row(lane) is not None:
                try:
                    gel_image = GelImage.objects.get(pk=lane.gel_image_id)
                    image_file = gel_image.display_file or gel_image.original_file
                    if image_file:
                        src = Image.open(image_file).convert("RGB")
                        # The outline's padded box, masked outside a tilted lane (lane_crop.py).
                        crop, crop_box = crop_lane(src, lane, 15, 3, 30, 3)
                        any_crop = True
                except Exception as e:
                    logger.warning(f"Failed to crop gel for lane {lane.lane_number}: {e}")

            lane_crops.append((crop, lane, crop_box))

        if not any_crop:
            return None

        # --- Determine uniform lane width ---
        LANE_WIDTH = 100

        # --- Build composite image (use RGBA for band overlay compositing) ---
        total_width = LANE_GAP + len(lanes) * (LANE_WIDTH + LANE_GAP)
        total_height = HEADER_HEIGHT + BODY_HEIGHT + FOOTER_HEIGHT

        img = Image.new("RGBA", (total_width, total_height), BG_COLOR + (255,))
        draw = ImageDraw.Draw(img)

        for i, (crop, lane, crop_box) in enumerate(lane_crops):
            col_x = LANE_GAP + i * (LANE_WIDTH + LANE_GAP)
            accent_color = ACCENT_COLORS[i % len(ACCENT_COLORS)]

            # Header background
            draw.rectangle([col_x, 0, col_x + LANE_WIDTH, HEADER_HEIGHT], fill=HEADER_BG + (255,))
            draw.rectangle([col_x, 0, col_x + LANE_WIDTH, ACCENT_BAR_HEIGHT], fill=accent_color + (255,))

            # Header label
            label = lane.sample_name[:14] if lane.sample_name else f"Lane {lane.lane_number}"
            lbl_bbox = draw.textbbox((0, 0), label, font=font_small)
            lbl_w = lbl_bbox[2] - lbl_bbox[0]
            draw.text(
                (col_x + (LANE_WIDTH - lbl_w) // 2, ACCENT_BAR_HEIGHT + 4),
                label,
                fill=TEXT_COLOR + (255,),
                font=font_small,
            )

            ln_label = f"L{lane.lane_number}"
            ln_bbox = draw.textbbox((0, 0), ln_label, font=font_small)
            ln_w = ln_bbox[2] - ln_bbox[0]
            draw.text(
                (col_x + (LANE_WIDTH - ln_w) // 2, ACCENT_BAR_HEIGHT + 4 + (lbl_bbox[3] - lbl_bbox[1]) + 2),
                ln_label,
                fill=TEXT_DIM + (255,),
                font=font_small,
            )

            # Lane body: paste cropped gel or draw placeholder
            if crop:
                resized = crop.resize((LANE_WIDTH, BODY_HEIGHT), Image.LANCZOS).convert("RGBA")
                img.paste(resized, (col_x, HEADER_HEIGHT))

                # Draw band overlays if requested
                if show_bands and crop_box and lane.bands:
                    cx1, cy1, cx2, cy2 = crop_box
                    crop_w = cx2 - cx1
                    crop_h = cy2 - cy1
                    # Scale factors from crop space to display space
                    sx = LANE_WIDTH / crop_w
                    sy = BODY_HEIGHT / crop_h

                    # Create overlay for this lane's bands
                    band_overlay = Image.new("RGBA", (LANE_WIDTH, BODY_HEIGHT), (0, 0, 0, 0))
                    band_draw = ImageDraw.Draw(band_overlay)

                    for band in lane.bands:
                        bx, by = band.bbox_x, band.bbox_y
                        bw, bh = band.bbox_width, band.bbox_height
                        if not all(v is not None for v in (bx, by, bw, bh)):
                            continue

                        # Transform from image coords to crop-relative coords, then scale
                        rx = (bx - cx1) * sx
                        ry = (by - cy1) * sy
                        rw = bw * sx
                        rh = bh * sy

                        # Clamp to lane body area
                        rx = max(0, min(rx, LANE_WIDTH))
                        ry = max(0, min(ry, BODY_HEIGHT))
                        rx2 = max(0, min(rx + rw, LANE_WIDTH))
                        ry2 = max(0, min(ry + rh, BODY_HEIGHT))

                        if rx2 - rx < 1 or ry2 - ry < 1:
                            continue

                        color = _band_overlay_color(band)
                        band_draw.rectangle(
                            [rx, ry, rx2, ry2],
                            fill=color,
                            outline=color[:3] + (200,),
                            width=1,
                        )

                        # MW label to the right (if calibrated and space allows)
                        if band.estimated_mw_kda and rx2 + 2 < LANE_WIDTH - 5:
                            mw_label = f"{band.estimated_mw_kda:.0f}"
                            mbbox = band_draw.textbbox((0, 0), mw_label, font=font_band)
                            mw_w = mbbox[2] - mbbox[0]
                            mw_h = mbbox[3] - mbbox[1]
                            mx = min(rx2 + 1, LANE_WIDTH - mw_w - 2)
                            my = ry + (ry2 - ry - mw_h) // 2
                            band_draw.rectangle(
                                [mx - 1, my - 1, mx + mw_w + 1, my + mw_h + 1],
                                fill=BAND_LABEL_BG,
                            )
                            band_draw.text((mx, my), mw_label, fill=BAND_LABEL_FG, font=font_band)

                    # Composite band overlay onto main image at lane position
                    img.alpha_composite(band_overlay, (col_x, HEADER_HEIGHT))

            else:
                # Dark placeholder with "No image" text
                draw.rectangle(
                    [col_x, HEADER_HEIGHT, col_x + LANE_WIDTH, HEADER_HEIGHT + BODY_HEIGHT], fill=(35, 35, 40, 255)
                )
                no_img = "No image"
                ni_bbox = draw.textbbox((0, 0), no_img, font=font_small)
                ni_w = ni_bbox[2] - ni_bbox[0]
                draw.text(
                    (col_x + (LANE_WIDTH - ni_w) // 2, HEADER_HEIGHT + BODY_HEIGHT // 2 - 5),
                    no_img,
                    fill=TEXT_DIM + (255,),
                    font=font_small,
                )

            # Footer: gel type
            footer_text = lane.gel_type[:14] if lane.gel_type else ""
            if footer_text:
                ft_bbox = draw.textbbox((0, 0), footer_text, font=font_small)
                ft_w = ft_bbox[2] - ft_bbox[0]
                draw.text(
                    (col_x + (LANE_WIDTH - ft_w) // 2, HEADER_HEIGHT + BODY_HEIGHT + 4),
                    footer_text,
                    fill=TEXT_DIM + (255,),
                    font=font_small,
                )

        # Convert to RGB for Word/PPTX compatibility
        result = img.convert("RGB")
        buf = BytesIO()
        result.save(buf, format="PNG")
        buf.seek(0)
        return buf

    def _render_lane_composite(self, lane, index):
        """
        Render a side-by-side composite: cropped real gel | digital lane | MW scale.

        Args:
            lane: ComparisonLaneData with geometry and gel_image_id
            index: Lane index for accent color

        Returns:
            BytesIO with PNG image, or None
        """
        import math

        from PIL import Image, ImageDraw, ImageFont

        from gel_analyzer.models import GelImage

        # --- Layout constants ---
        BODY_HEIGHT = 400
        HEADER_HEIGHT = 28
        FOOTER_HEIGHT = 0
        DIGITAL_WIDTH = 100
        MW_SCALE_WIDTH = 65
        GAP = 8
        BAND_HEIGHT = 8
        BAND_INSET = int(DIGITAL_WIDTH * 0.10)
        ACCENT_BAR_HEIGHT = 4

        # --- Colors (same as digital gel) ---
        BG_COLOR = (30, 30, 34)
        LANE_BG = (42, 42, 46)
        HEADER_BG = (26, 26, 30)
        TEXT_COLOR = (230, 230, 230)
        TEXT_DIM = (160, 160, 160)
        SCALE_LINE = (80, 80, 85)

        # Band fill RGB picked by ENUM CODE (POI=purple, MW_REFERENCE=orange, OTHER=green)
        from .constants import BAND_PALETTE

        def _band_rgb(b):
            return BAND_PALETTE.get((b.band_type_code or "OTHER").upper(), BAND_PALETTE["OTHER"])["stroke"][:3]

        ACCENT_COLORS = [
            (37, 99, 235),  # accent-600
            (168, 85, 247),
            (34, 197, 94),
            (249, 115, 22),
            (236, 72, 153),
            (20, 184, 166),
            (245, 158, 11),
            (99, 102, 241),
        ]
        STANDARD_MWS = [10, 15, 20, 25, 37, 50, 75, 100, 150, 250]

        accent_color = ACCENT_COLORS[index % len(ACCENT_COLORS)]

        # --- Compute MW range from this lane's bands: no MW, no MW scale ---
        all_mws = [b.estimated_mw_kda for b in lane.bands if b.estimated_mw_kda and b.estimated_mw_kda > 0]
        has_mw = len(all_mws) > 0

        if has_mw:
            log_min = math.log10(min(all_mws))
            log_max = math.log10(max(all_mws))
            log_range = log_max - log_min
            if log_range < 0.1:
                log_range = 0.5
            log_min -= log_range * 0.15
            log_max += log_range * 0.15
            log_span = log_max - log_min
            mw_min = 10**log_min
            mw_max = 10**log_max

        # --- Fonts ---
        try:
            font = ImageFont.truetype("arial.ttf", 11)
            font_small = ImageFont.truetype("arial.ttf", 10)
        except OSError:
            try:
                font = ImageFont.truetype("/System/Library/Fonts/Helvetica.ttc", 11)
                font_small = ImageFont.truetype("/System/Library/Fonts/Helvetica.ttc", 10)
            except OSError:
                font = ImageFont.load_default()
                font_small = font

        def mw_to_y(mw_kda):
            log_mw = math.log10(max(mw_kda, 1))
            fraction = (log_max - log_mw) / log_span
            fraction = max(0.02, min(0.98, fraction))
            return HEADER_HEIGHT + int(fraction * BODY_HEIGHT)

        def position_to_y(pos_y, rows):
            # Band.position_y is an absolute image row. `rows` are the image rows
            # (top, bottom) the gel crop shows, stretched over the full column height:
            # on that scale a mark sits level with its band in the crop.
            if not rows or rows[1] <= rows[0]:
                return HEADER_HEIGHT + BODY_HEIGHT // 2
            y = int((pos_y - rows[0]) / (rows[1] - rows[0]) * (HEADER_HEIGHT + BODY_HEIGHT + FOOTER_HEIGHT))
            return max(HEADER_HEIGHT + int(0.02 * BODY_HEIGHT), min(HEADER_HEIGHT + int(0.98 * BODY_HEIGHT), y))

        # Image rows of the lane's outline box with small padding (as crop_lane pads it): the crop's rows, and the
        # scale of the bands without an MW.
        crop_rows = None
        outline = outline_of_row(lane)
        if outline is not None:
            _, outline_y, _, outline_h = outer_bbox(outline)
            pad_y = max(5, outline_h // 20)
            crop_rows = (max(0, outline_y - pad_y), outline_y + outline_h + pad_y)

        # --- 1. Crop real gel image ---
        gel_crop = None
        gel_crop_width = 0
        if lane.gel_image_id and crop_rows:
            try:
                gel_image = GelImage.objects.get(pk=lane.gel_image_id)
                image_file = gel_image.display_file or gel_image.original_file
                if image_file:
                    src = Image.open(image_file).convert("RGB")
                    # The lane's outline box with small padding, masked outside a tilted lane (lane_crop.py); the
                    # rows it shows, clipped to the image, are the bands' scale
                    gel_crop, crop_box = crop_lane(src, lane, 10, 5, 20, 5)
                    crop_rows = (crop_box[1], crop_box[3])

                    # Resize to match BODY_HEIGHT, preserving aspect ratio
                    crop_h = HEADER_HEIGHT + BODY_HEIGHT + FOOTER_HEIGHT
                    aspect = gel_crop.width / gel_crop.height
                    crop_w = max(60, int(crop_h * aspect))
                    gel_crop = gel_crop.resize((crop_w, crop_h), Image.LANCZOS)
                    gel_crop_width = crop_w
            except Exception as e:
                logger.warning(f"Failed to crop gel image for lane {lane.lane_number}: {e}")

        # --- 2. Render digital lane column ---
        digital_total_h = HEADER_HEIGHT + BODY_HEIGHT + FOOTER_HEIGHT
        digital_img = Image.new("RGB", (DIGITAL_WIDTH, digital_total_h), BG_COLOR)
        dd = ImageDraw.Draw(digital_img)

        # Column background
        dd.rectangle([0, HEADER_HEIGHT, DIGITAL_WIDTH, HEADER_HEIGHT + BODY_HEIGHT], fill=LANE_BG)
        # Header
        dd.rectangle([0, 0, DIGITAL_WIDTH, HEADER_HEIGHT], fill=HEADER_BG)
        dd.rectangle([0, 0, DIGITAL_WIDTH, ACCENT_BAR_HEIGHT], fill=accent_color)
        # Header label
        lbl = "Digital"
        lbl_bbox = dd.textbbox((0, 0), lbl, font=font_small)
        lbl_w = lbl_bbox[2] - lbl_bbox[0]
        dd.text(((DIGITAL_WIDTH - lbl_w) // 2, ACCENT_BAR_HEIGHT + 4), lbl, fill=TEXT_COLOR, font=font_small)

        # Draw bands
        for band in lane.bands:
            if has_mw and band.estimated_mw_kda and band.estimated_mw_kda > 0:
                y_center = mw_to_y(band.estimated_mw_kda)
            elif band.position_y is not None:
                y_center = position_to_y(band.position_y, crop_rows)
            else:
                continue

            base_color = _band_rgb(band)
            opacity = 0.7
            if band.relative_percent_lane is not None:
                opacity = max(0.4, min(1.0, band.relative_percent_lane / 40.0))
            blended = tuple(int(base_color[c] * opacity + LANE_BG[c] * (1 - opacity)) for c in range(3))
            bx1 = BAND_INSET
            bx2 = DIGITAL_WIDTH - BAND_INSET
            by1 = y_center - BAND_HEIGHT // 2
            by2 = y_center + BAND_HEIGHT // 2
            dd.rectangle([bx1, by1, bx2, by2], fill=blended)
            highlight = tuple(min(255, c + 40) for c in blended)
            dd.rectangle([bx1, y_center - 1, bx2, y_center + 1], fill=highlight)

        # --- 3. Render MW scale column ---
        scale_img = Image.new("RGB", (MW_SCALE_WIDTH, digital_total_h), BG_COLOR)
        sd = ImageDraw.Draw(scale_img)

        if has_mw:
            visible_mws = [mw for mw in STANDARD_MWS if mw_min <= mw <= mw_max]
            if not visible_mws:
                visible_mws = [round(min(all_mws)), round(max(all_mws))]

            for mw in visible_mws:
                y = mw_to_y(mw)
                sd.line([(0, y), (8, y)], fill=SCALE_LINE, width=1)
                mw_label = f"{mw} kDa"
                sd.text((10, y - 6), mw_label, fill=TEXT_DIM, font=font_small)
        else:
            # No band carries an MW: the marks sit on the crop's rows (position_to_y),
            # which no kDa ruler describes -- a tick beside a band would read as an MW
            # the lab never estimated.
            for i, text in enumerate(("No MW", "calibration")):
                text_bbox = sd.textbbox((0, 0), text, font=font_small)
                text_w = text_bbox[2] - text_bbox[0]
                sd.text(
                    ((MW_SCALE_WIDTH - text_w) // 2, HEADER_HEIGHT + 8 + i * 13), text, fill=TEXT_DIM, font=font_small
                )

        sd.text((10, HEADER_HEIGHT - 14), "MW", fill=TEXT_COLOR, font=font)

        # --- 4. Stitch together: [gel_crop | gap | digital | gap | mw_scale] ---
        parts = []
        if gel_crop:
            parts.append(("gel", gel_crop))
        parts.append(("digital", digital_img))
        parts.append(("scale", scale_img))

        total_w = sum(p[1].width for p in parts) + GAP * (len(parts) - 1)
        total_h = digital_total_h

        # Add labels row above if gel crop present
        LABEL_HEIGHT = 20 if gel_crop else 0
        composite = Image.new("RGB", (total_w, total_h + LABEL_HEIGHT), BG_COLOR)
        cd = ImageDraw.Draw(composite)

        # Draw labels
        if gel_crop and LABEL_HEIGHT > 0:
            cd.text((gel_crop_width // 2 - 20, 2), "Gel Image", fill=TEXT_DIM, font=font_small)
            digital_start = gel_crop_width + GAP
            cd.text((digital_start + DIGITAL_WIDTH // 2 - 16, 2), "Digital", fill=TEXT_DIM, font=font_small)

        x_offset = 0
        for _name, part_img in parts:
            composite.paste(part_img, (x_offset, LABEL_HEIGHT))
            x_offset += part_img.width + GAP

        # Draw thin separator lines between panels
        if gel_crop:
            sep_x = gel_crop_width + GAP // 2
            cd.line([(sep_x, LABEL_HEIGHT), (sep_x, total_h + LABEL_HEIGHT)], fill=SCALE_LINE, width=1)

        buf = BytesIO()
        composite.save(buf, format="PNG")
        buf.seek(0)
        return buf

