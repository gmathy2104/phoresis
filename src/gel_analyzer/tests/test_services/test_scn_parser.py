"""
Tests for the SCN parser service.

Tests use synthetic .scn fixtures that mirror the real Bio-Rad nested MIME
structure: top-level parts (ItemHeaderTag, ScanImageTag0, ItemProtocolSettingsTag)
with ImageData and ImageHeader nested inside ScanImageTag0.
"""

import tempfile
from pathlib import Path

import numpy as np

from django.test import SimpleTestCase

from gel_analyzer.services.file_handler import GelFileHandler
from gel_analyzer.services.scn_parser import SCNParseError, SCNParser


def build_scn_file(
    width=10,
    height=8,
    pixel_value=1000,
    endian="little",
    zero_is="white",
    scanner_model="ChemiDoc MP",
    exposure_time="5.0",
    filter_name="590/110 Filter",
    application="Coomassie Blue",
    include_image_data=True,
    include_image_header=True,
    truncate_data=False,
) -> bytes:
    """
    Build a synthetic .scn file matching real Bio-Rad nested MIME structure.

    Structure::
        Top-level (boundary_outer)
        ├── ItemHeaderTag (XML)
        ├── ScanImageTag0 (nested multipart, boundary_inner)
        │   ├── ImageData (binary)
        │   └── ImageHeader (XML)
        └── ItemProtocolSettingsTag (XML)
    """
    boundary_outer = "OUTER_BOUNDARY_TEST_123"
    boundary_inner = "INNER_BOUNDARY_TEST_456"

    # Build raw image data
    dtype = "<u2" if endian == "little" else ">u2"
    img = np.full((height, width), pixel_value, dtype=dtype)
    image_data = img.tobytes()
    if truncate_data:
        image_data = image_data[: len(image_data) // 2]

    # ImageHeader XML — matches real Bio-Rad format (name/value attributes)
    image_header_xml = (
        f"<!DOCTYPE XML>\n"
        f"<root>\n"
        f"  <endian>{endian}</endian>\n"
        f'  <size_pix width="{width}" height="{height}"/>\n'
        f'  <image zero_is="{zero_is}"/>\n'
        f'  <size_mm width="210" height="168" known="true"/>\n'
        f"  <scan_attributes>\n"
        f'    <imager type="0" name="Imager" value="{scanner_model}"/>\n'
        f'    <exposure_time type="1" name="Exposure Time (sec)" value="{exposure_time}"/>\n'
        f'    <application type="0" name="Application" value="{application}"/>\n'
        f'    <emission_filter type="0" name="Emission Filter" value="{filter_name}"/>\n'
        f'    <serial_number type="0" name="Serial Number" value="733BR-TEST"/>\n'
        f"  </scan_attributes>\n"
        f"</root>"
    ).encode()

    # ItemHeaderTag XML
    item_header_xml = (
        b'<!DOCTYPE XML>\n<root version="2">\n  <name>Test Scan 001</name>\n  <user>testuser</user>\n</root>'
    )

    # Protocol XML
    protocol_xml = (
        b'<?xml version="1.0" encoding="UTF-8"?>\n'
        b"<protocol>\n"
        b"  <protocol_name>Test Protocol</protocol_name>\n"
        b"  <resolution>100 micron</resolution>\n"
        b"</protocol>"
    )

    # ── Build nested ScanImageTag0 body ──
    inner_body = b""
    if include_image_data:
        inner_body += f"--{boundary_inner}\r\n".encode()
        inner_body += b"Content-Type: application/octet-stream\r\n"
        inner_body += f"Content-Length: {len(image_data)}\r\n".encode()
        inner_body += b"Content-Description: ImageData\r\n"
        inner_body += b"\r\n"
        inner_body += image_data
        inner_body += b"\r\n"

    if include_image_header:
        inner_body += f"--{boundary_inner}\r\n".encode()
        inner_body += b'Content-Type: text/xml; charset="utf8"\r\n'
        inner_body += f"Content-Length: {len(image_header_xml)}\r\n".encode()
        inner_body += b"Content-Description: ImageHeader\r\n"
        inner_body += b"\r\n"
        inner_body += image_header_xml
        inner_body += b"\r\n"

    inner_body += f"--{boundary_inner}--\r\n".encode()

    # ── Build top-level MIME ──
    result = (
        f"MIME-Version: 1.0 (Generated by Test)\r\n"
        f'Content-Type: multipart/mixed; boundary="{boundary_outer}"\r\n'
        f"Content-Description: Image Lab Image File\r\n"
        f"\r\n"
    ).encode()

    # Part 1: ItemHeaderTag
    result += f"--{boundary_outer}\r\n".encode()
    result += b'Content-Type: text/xml; charset="utf8"\r\n'
    result += f"Content-Length: {len(item_header_xml)}\r\n".encode()
    result += b"Content-Description: ItemHeaderTag\r\n"
    result += b"\r\n"
    result += item_header_xml
    result += b"\r\n"

    # Part 2: ScanImageTag0 (nested multipart)
    result += f"--{boundary_outer}\r\n".encode()
    result += f'Content-Type: multipart/mixed; boundary="{boundary_inner}"\r\n'.encode()
    result += f"Content-Length: {len(inner_body)}\r\n".encode()
    result += b"Content-Description: ScanImageTag0\r\n"
    result += b"\r\n"
    result += inner_body
    result += b"\r\n"

    # Part 3: ItemProtocolSettingsTag
    result += f"--{boundary_outer}\r\n".encode()
    result += b'Content-Type: text/xml; charset="utf8"\r\n'
    result += f"Content-Length: {len(protocol_xml)}\r\n".encode()
    result += b"Content-Description: ItemProtocolSettingsTag\r\n"
    result += b"\r\n"
    result += protocol_xml
    result += b"\r\n"

    # Closing boundary
    result += f"--{boundary_outer}--\r\n".encode()

    return result


class TestSCNParserIsScnFile(SimpleTestCase):
    """Tests for SCNParser.is_scn_file()."""

    def test_positive_scn_file(self):
        """A valid SCN file should be detected."""
        data = build_scn_file()
        with tempfile.NamedTemporaryFile(suffix=".scn", delete=False) as f:
            f.write(data)
            path = Path(f.name)
        try:
            self.assertTrue(SCNParser.is_scn_file(path))
        finally:
            path.unlink()

    def test_negative_png_file(self):
        """A PNG file should not be detected as SCN."""
        with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as f:
            f.write(b"\x89PNG\r\n\x1a\n" + b"\x00" * 100)
            path = Path(f.name)
        try:
            self.assertFalse(SCNParser.is_scn_file(path))
        finally:
            path.unlink()

    def test_negative_tiff_file(self):
        """A TIFF file should not be detected as SCN."""
        with tempfile.NamedTemporaryFile(suffix=".tif", delete=False) as f:
            f.write(b"II\x2a\x00" + b"\x00" * 100)
            path = Path(f.name)
        try:
            self.assertFalse(SCNParser.is_scn_file(path))
        finally:
            path.unlink()

    def test_nonexistent_file(self):
        """A nonexistent file should return False."""
        self.assertFalse(SCNParser.is_scn_file(Path("/nonexistent/file.scn")))


class TestSCNParserParse(SimpleTestCase):
    """Tests for SCNParser.parse()."""

    def _write_scn(self, data: bytes) -> Path:
        with tempfile.NamedTemporaryFile(suffix=".scn", delete=False) as f:
            f.write(data)
        return Path(f.name)

    def test_parse_basic(self):
        """Parse a valid SCN file and verify shape/dtype/values."""
        data = build_scn_file(width=10, height=8, pixel_value=42000)
        path = self._write_scn(data)
        try:
            img, meta = SCNParser.parse(path)
            self.assertEqual(img.shape, (8, 10))
            self.assertEqual(img.dtype, np.dtype("<u2"))
            # Raw pixels returned as-is (no inversion in parser)
            np.testing.assert_array_equal(img, 42000)
        finally:
            path.unlink()

    def test_parse_no_inversion_when_zero_is_black(self):
        """When zero_is=black, pixel values should NOT be inverted."""
        data = build_scn_file(width=5, height=4, pixel_value=10000, zero_is="black")
        path = self._write_scn(data)
        try:
            img, meta = SCNParser.parse(path)
            np.testing.assert_array_equal(img, 10000)
        finally:
            path.unlink()

    def test_parse_big_endian(self):
        """Parse a big-endian SCN file."""
        data = build_scn_file(width=4, height=3, pixel_value=500, endian="big")
        path = self._write_scn(data)
        try:
            img, meta = SCNParser.parse(path)
            self.assertEqual(img.shape, (3, 4))
            self.assertEqual(meta["endianness"], "big")
            # Raw pixels returned as-is (no inversion in parser)
            np.testing.assert_array_equal(img, 500)
        finally:
            path.unlink()

    def test_metadata_extraction(self):
        """Verify all metadata fields are extracted."""
        data = build_scn_file(
            scanner_model="ChemiDoc MP",
            exposure_time="10.0",
            filter_name="Cy5 Filter",
            application="Western Blot",
        )
        path = self._write_scn(data)
        try:
            _, meta = SCNParser.parse(path)
            self.assertEqual(meta["source"], "Bio-Rad SCN")
            self.assertEqual(meta["bit_depth"], 16)
            self.assertEqual(meta["scanner_model"], "ChemiDoc MP")
            self.assertEqual(meta["exposure_time"], "10.0")
            self.assertEqual(meta["filter"], "Cy5 Filter")
            self.assertEqual(meta["application"], "Western Blot")
            self.assertEqual(meta["scan_name"], "Test Scan 001")
            self.assertEqual(meta["user"], "testuser")
            self.assertEqual(meta["protocol_name"], "Test Protocol")
            self.assertEqual(meta["resolution"], "100 micron")
            self.assertEqual(meta["serial_number"], "733BR-TEST")
            self.assertEqual(meta["physical_size_mm"], "210 x 168 mm")
        finally:
            path.unlink()

    def test_error_not_scn(self):
        """Parsing a non-SCN file should raise SCNParseError."""
        path = self._write_scn(b"\x89PNG\r\n\x1a\n" + b"\x00" * 100)
        try:
            with self.assertRaises(SCNParseError):
                SCNParser.parse(path)
        finally:
            path.unlink()

    def test_error_missing_image_data(self):
        """SCN without ImageData part should raise SCNParseError."""
        data = build_scn_file(include_image_data=False)
        path = self._write_scn(data)
        try:
            with self.assertRaises(SCNParseError):
                SCNParser.parse(path)
        finally:
            path.unlink()

    def test_error_missing_image_header(self):
        """SCN without ImageHeader part should raise SCNParseError."""
        data = build_scn_file(include_image_header=False)
        path = self._write_scn(data)
        try:
            with self.assertRaises(SCNParseError):
                SCNParser.parse(path)
        finally:
            path.unlink()

    def test_error_truncated_data(self):
        """SCN with truncated pixel data should raise SCNParseError."""
        data = build_scn_file(truncate_data=True)
        path = self._write_scn(data)
        try:
            with self.assertRaises(SCNParseError):
                SCNParser.parse(path)
        finally:
            path.unlink()

    def test_error_nonexistent_file(self):
        """Parsing a nonexistent file should raise SCNParseError."""
        with self.assertRaises(SCNParseError):
            SCNParser.parse(Path("/nonexistent/file.scn"))


class TestFileHandlerSCNIntegration(SimpleTestCase):
    """Test SCN integration with GelFileHandler."""

    def _write_scn(self, data: bytes) -> Path:
        with tempfile.NamedTemporaryFile(suffix=".scn", delete=False) as f:
            f.write(data)
        return Path(f.name)

    def test_detect_format_scn(self):
        """GelFileHandler.detect_format() should return 'SCN' for .scn files."""
        data = build_scn_file()
        path = self._write_scn(data)
        try:
            fmt = GelFileHandler.detect_format(path)
            self.assertEqual(fmt, "SCN")
        finally:
            path.unlink()

    def test_read_image_scn(self):
        """GelFileHandler.read_image() should return correct array and metadata for SCN."""
        data = build_scn_file(width=6, height=4, pixel_value=30000)
        path = self._write_scn(data)
        try:
            img, meta = GelFileHandler.read_image(path)
            self.assertEqual(img.shape, (4, 6))
            self.assertEqual(meta["format"], "SCN")
            self.assertEqual(meta["bit_depth"], 16)
            self.assertEqual(meta["width"], 6)
            self.assertEqual(meta["height"], 4)
            self.assertIn("scn_metadata", meta)
            # Raw pixels returned as-is (no inversion in parser)
            np.testing.assert_array_equal(img, 30000)
        finally:
            path.unlink()

    def test_process_uploaded_file_scn(self):
        """GelFileHandler.process_uploaded_file() should produce display + thumbnail for SCN."""
        data = build_scn_file(width=20, height=15, pixel_value=50000)
        path = self._write_scn(data)
        try:
            result = GelFileHandler.process_uploaded_file(path)
            self.assertIn("display_bytes", result)
            self.assertIn("thumbnail_bytes", result)
            self.assertGreater(len(result["display_bytes"]), 0)
            self.assertGreater(len(result["thumbnail_bytes"]), 0)
            self.assertEqual(result["metadata"]["format"], "SCN")
        finally:
            path.unlink()

    def test_scn_in_supported_extensions(self):
        """'.scn' should be in SUPPORTED_EXTENSIONS."""
        self.assertIn(".scn", GelFileHandler.SUPPORTED_EXTENSIONS)

    def test_format_from_extension_scn(self):
        """_format_from_extension should map '.scn' to 'SCN'."""
        self.assertEqual(GelFileHandler._format_from_extension(".scn"), "SCN")
